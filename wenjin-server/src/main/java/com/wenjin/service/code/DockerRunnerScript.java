package com.wenjin.service.code;

/**
 * 容器内两段 runner 脚本（POSIX sh，内容固定、参数只有数字）与它们的退出码约定。
 *
 * <h2>执行模型（「编译一次 + 每用例一个容器」，见 {@link DockerCodeSandbox}）</h2>
 * <ol>
 *   <li><b>编译容器</b>：{@code /wj/compile.sh <heapMb>}。只挂载源码目录（只读，/src）、本次运行的 class 输出目录
 *       （<b>唯一</b>可写挂载，/classes）与脚本目录（只读，/wj）。{@code javac -proc:none}（不跑注解处理器，
 *       编译阶段不执行任何学生代码），诊断合并到 stdout；{@code umask 000} 让产物对宿主应用账户可删。</li>
 *   <li><b>用例容器</b>（每个用例一个）：{@code /wj/case.sh <limBytes> <heapMb>}。只挂载 class 目录（只读）、
 *       <b>该用例自己</b>的输入目录（只读，/in/stdin.txt）与脚本目录（只读）——别的用例（含 hidden）的输入
 *       从不出现在这个容器里。学生程序的 stdout 经 {@code head -c} 截断后就是容器 stdout，stderr 经 FIFO 同样截断后
 *       就是容器 stderr；脚本以学生程序的退出码退出。</li>
 * </ol>
 *
 * <h2>信任边界</h2>
 * 用例容器里学生代码与脚本同为 uid 65534，学生可以篡改 /tmp 下的任何东西、向 PID 1 发信号、经
 * {@code /proc/1/fd/1} 直写容器 stdout、{@code setsid} 逃出进程组——但这些都只能影响<b>它自己这个用例</b>的
 * 结果：宿主自己测墙钟（{@link ProcessRunner.Result#elapsedMs()}）、自己判超时、自己截断 stdout/stderr
 * （读取上限 = output-max-bytes+1）、自己与期望输出比对；期望输出从不进入任何容器。容器 PID 1 是
 * {@code timeout -s KILL <run>}（命名空间内的 init 不接受同命名空间发来的 SIGKILL/SIGSTOP），到期后整个 PID
 * 命名空间被内核回收，逃逸的子进程一并结束。
 *
 * <h2>退出码约定（宿主侧解释）</h2>
 * <ul>
 *   <li>{@value #EXIT_ENV}：脚本自检失败（缺 java/javac/head/mkfifo 等）或 docker 自身/运行时失败
 *       （docker CLI 的 125/126/127）→ 基础设施失败。</li>
 *   <li>case.sh 把学生程序的退出码规整到 0–255 且<b>把 124–127 改写为 1</b>：学生无法伪造 docker 的 125–127
 *       （否则可把「答错」变成「未判分」）。被信号杀死的脚本经 PID 1 的 timeout 回报为 128+信号（≥129）。</li>
 *   <li>超时一律以宿主测得的墙钟判定，容器内的 124/137 只作参考。</li>
 * </ul>
 */
final class DockerRunnerScript {

    /** 脚本自检失败的退出码（与 docker CLI 的「docker run 自身失败」同码，宿主一律视为基础设施失败） */
    static final int EXIT_ENV = 125;

    static final String COMPILE_SH = "compile.sh";
    static final String CASE_SH = "case.sh";

    private DockerRunnerScript() {
    }

    /** 编译脚本：{@code sh /wj/compile.sh <heapMb>}。 */
    static String compileScript() {
        return """
                #!/bin/sh
                # wenjin code sandbox: compile step (generated by host; mounted read-only at /wj)
                # usage: compile.sh <heapMb>
                HEAP=$1
                case "$HEAP" in ''|*[!0-9]*) exit 125 ;; esac
                command -v javac >/dev/null 2>&1 || exit 125
                unset JAVA_TOOL_OPTIONS JDK_JAVA_OPTIONS _JAVA_OPTIONS CLASSPATH
                export HOME=/tmp LANG=C.UTF-8
                umask 000
                exec javac -J-Xmx${HEAP}m -J-XX:+UseSerialGC -J-XX:TieredStopAtLevel=1 -J-XX:-UsePerfData \\
                  -proc:none -encoding UTF-8 -nowarn -d /classes /src/Main.java 2>&1
                """;
    }

    /** 用例脚本：{@code sh /wj/case.sh <limBytes> <heapMb>}，标准输入来自 /in/stdin.txt。 */
    static String caseScript() {
        return """
                #!/bin/sh
                # wenjin code sandbox: one test case (generated by host; mounted read-only at /wj)
                # usage: case.sh <limBytes> <heapMb>    stdin: /in/stdin.txt    exit: student's exit code (sanitised)
                LIM=$1
                HEAP=$2
                case "$LIM$HEAP" in ''|*[!0-9]*) exit 125 ;; esac
                for t in java head mkfifo cat; do
                  command -v "$t" >/dev/null 2>&1 || exit 125
                done
                [ -r /in/stdin.txt ] || exit 125
                unset JAVA_TOOL_OPTIONS JDK_JAVA_OPTIONS _JAVA_OPTIONS CLASSPATH
                export HOME=/tmp LANG=C.UTF-8
                T=/tmp/wj
                mkdir -p "$T" && rm -f "$T/ef" "$T/rc" && mkfifo "$T/ef" || exit 125
                head -c "$LIM" < "$T/ef" >&2 &
                { java -Xmx${HEAP}m -Xss8m -XX:+UseSerialGC -XX:TieredStopAtLevel=1 -XX:-UsePerfData \\
                    -XX:+ExitOnOutOfMemoryError -Dfile.encoding=UTF-8 -Dstdout.encoding=UTF-8 -Dstderr.encoding=UTF-8 \\
                    -cp /classes Main < /in/stdin.txt 2> "$T/ef"; echo "$?" > "$T/rc"; } | head -c "$LIM"
                wait
                r=$(cat "$T/rc" 2>/dev/null)
                # /tmp is writable by the student: accept 1-3 digits only, clamp, and never let it look like docker's 124-127
                case "$r" in ''|*[!0-9]*|????*) r=255 ;; esac
                if [ "$r" -gt 255 ]; then r=255; fi
                if [ "$r" -ge 124 ] && [ "$r" -le 127 ]; then r=1; fi
                exit "$r"
                """;
    }

    /** 宿主读取单个用例 stdout / stderr 的字节上限：output-max-bytes + 1（多 1 字节用于判定「超限」）。 */
    static int caseOutputCap(SandboxLimits l) {
        return (int) Math.min(Integer.MAX_VALUE - 8, (long) l.outputMaxBytes() + 1);
    }

    /** docker CLI 自身失败（125）、命令不可执行（126）、命令不存在（127）——以及脚本自检失败（125）。 */
    static boolean isInfrastructureExit(int exitCode) {
        return exitCode >= 125 && exitCode <= 127;
    }
}
