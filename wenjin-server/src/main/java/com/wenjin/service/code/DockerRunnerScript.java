package com.wenjin.service.code;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Base64;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * 容器内 runner 脚本（POSIX sh）的生成与其输出协议的解析。
 *
 * <h2>执行模型</h2>
 * 单个容器内：{@code javac} 编译一次（{@code timeout -s KILL <compile>}），再对每个用例
 * {@code timeout -s KILL <run> java ... Main < /work/in/<i>.txt}；学生程序的 stdout 经管道 {@code head -c}
 * 截到 output-max-bytes+1 字节写入 /tmp 文件，stderr 经 FIFO 同样截断。依赖的
 * {@code timeout/head/base64/date/mkfifo} 均来自 coreutils（eclipse-temurin 为 Ubuntu 基础镜像，coreutils 为必备包）；
 * 脚本启动时自检，缺任何一个即 {@code FATAL}。
 *
 * <h2>协议（runner → 宿主，经 docker run 的 stdout）</h2>
 * <pre>
 * @@WJ1 BEGIN
 * @@WJ1 FATAL &lt;reason&gt;                               （运行环境不满足，之后无其它行）
 * @@WJ1 COMPILE &lt;rc&gt; &lt;b64(compile output)|-&gt;
 * @@WJ1 CASE &lt;i&gt; &lt;rc&gt; &lt;ms&gt; &lt;b64(stdout)|-&gt; &lt;b64(stderr)|-&gt;   （每用例一行）
 * @@WJ1 END
 * </pre>
 * {@code rc=124} 表示触及墙钟上限：GNU {@code timeout -s KILL} 会把 SIGKILL 发给整个进程组（连同 timeout 自身），
 * 此时返回 137 而不是 124，与 cgroup OOM 杀进程同码；脚本按「137 且耗时 ≥ 上限」改写为 124，
 * 其余 137 视为被内核杀死（内存超限）。
 * 数据字段一律 base64（空为 {@code -}），学生输出永远不以原文出现在 docker stdout，不会与协议行混淆。
 * 期望输出<b>从不</b>进入容器（比对在宿主侧），因此即便学生代码伪造协议行，也只能影响自己的结果呈现，
 * 无法得知 hidden 用例的期望答案。
 */
final class DockerRunnerScript {

    static final String MARK = "@@WJ1";

    private DockerRunnerScript() {
    }

    /** 解析结果。cases 已按 output-max-bytes 截断。 */
    record Parsed(boolean begun,
                  boolean ended,
                  String fatal,
                  Integer compileExitCode,
                  String compileOutput,
                  List<SandboxResult.CaseRun> cases) {
    }

    static String render(SandboxLimits l, int caseCount) {
        String header = String.format(Locale.ROOT, """
                #!/bin/sh
                # wenjin code sandbox runner v1 (generated by host; mounted read-only at /work)
                N=%d
                CT=%d
                RT=%d
                LIM=%d
                HEAP=%d
                """, caseCount, l.compileTimeoutSeconds(), l.runTimeoutSeconds(),
                (long) l.outputMaxBytes() + 1, l.jvmHeapMb());
        return header + BODY;
    }

    private static final String BODY = """
            W=/work
            T=/tmp
            unset JAVA_TOOL_OPTIONS JDK_JAVA_OPTIONS _JAVA_OPTIONS CLASSPATH
            export HOME=/tmp LANG=C.UTF-8
            JOPTS="-Xmx${HEAP}m -XX:+UseSerialGC -XX:TieredStopAtLevel=1 -XX:-UsePerfData"
            b64() { if [ -s "$1" ]; then base64 -w 0 "$1"; else printf '%s' '-'; fi; }
            now_ms() { echo $(( $(date +%s%N) / 1000000 )); }
            echo "@@WJ1 BEGIN"
            for t in timeout head base64 date mkfifo javac java; do
              command -v "$t" >/dev/null 2>&1 || { echo "@@WJ1 FATAL missing-$t"; exit 0; }
            done
            mkdir -p "$T/out" || { echo "@@WJ1 FATAL tmp-not-writable"; exit 0; }
            c0=$(now_ms)
            timeout -s KILL "$CT" javac -J-Xmx${HEAP}m -J-XX:+UseSerialGC -J-XX:TieredStopAtLevel=1 -J-XX:-UsePerfData \\
              -encoding UTF-8 -nowarn -d "$T/out" "$W/Main.java" > "$T/compile.log" 2>&1
            rc=$?
            c1=$(now_ms)
            # timeout -s KILL 会连自己一起杀掉（退出码 137 而非 124）；按耗时把墙钟超时统一归为 124
            if [ "$rc" -eq 137 ] && [ $((c1 - c0)) -ge $((CT * 1000)) ]; then rc=124; fi
            head -c "$LIM" "$T/compile.log" > "$T/compile.cut"
            echo "@@WJ1 COMPILE $rc $(b64 "$T/compile.cut")"
            if [ "$rc" -ne 0 ]; then echo "@@WJ1 END"; exit 0; fi
            i=0
            while [ "$i" -lt "$N" ]; do
              rm -f "$T/rc" "$T/so" "$T/se" "$T/ef"
              mkfifo "$T/ef" || { echo "@@WJ1 FATAL mkfifo"; exit 0; }
              head -c "$LIM" < "$T/ef" > "$T/se" &
              hp=$!
              t0=$(now_ms)
              { timeout -s KILL "$RT" java $JOPTS -Xss8m -XX:+ExitOnOutOfMemoryError -Dfile.encoding=UTF-8 \\
                  -Dstdout.encoding=UTF-8 -Dstderr.encoding=UTF-8 -cp "$T/out" Main < "$W/in/$i.txt" 2> "$T/ef"; \\
                echo "$?" > "$T/rc"; } | head -c "$LIM" > "$T/so"
              t1=$(now_ms)
              wait "$hp"
              r=$(cat "$T/rc" 2>/dev/null)
              [ -n "$r" ] || r=255
              if [ "$r" -eq 137 ] && [ $((t1 - t0)) -ge $((RT * 1000)) ]; then r=124; fi
              echo "@@WJ1 CASE $i $r $((t1 - t0)) $(b64 "$T/so") $(b64 "$T/se")"
              i=$((i + 1))
            done
            echo "@@WJ1 END"
            """;

    /**
     * 宿主读取 docker stdout 的字节上限：编译输出 + 每用例 stdout/stderr 各一份满额 base64 + 行开销。
     * 超过即说明输出被篡改/灌水，多余部分丢弃。
     */
    static int hostStdoutCap(SandboxLimits l, int caseCount) {
        long field = ((long) l.outputMaxBytes() + 1 + 2) / 3 * 4 + 1;
        long total = (2L * caseCount + 1) * (field + 64) + 4096;
        return (int) Math.min(Integer.MAX_VALUE - 8, total);
    }

    static Parsed parse(byte[] stdout, int outputMaxBytes) {
        if (stdout == null || stdout.length == 0) {
            return new Parsed(false, false, null, null, null, List.of());
        }
        String text = new String(stdout, StandardCharsets.ISO_8859_1); // 协议行纯 ASCII
        boolean begun = false;
        boolean ended = false;
        String fatal = null;
        Integer compileRc = null;
        String compileOut = null;
        List<SandboxResult.CaseRun> cases = new ArrayList<>();
        Set<Integer> seen = new HashSet<>();
        for (String raw : text.split("\n")) {
            String line = raw.strip();
            if (!line.startsWith(MARK + " ")) {
                continue;
            }
            String[] f = line.split(" ");
            String kind = f.length > 1 ? f[1] : "";
            if (!begun) {
                if (kind.equals("BEGIN")) {
                    begun = true;
                }
                continue;
            }
            switch (kind) {
                case "FATAL" -> {
                    if (fatal == null) {
                        fatal = f.length > 2 ? String.join(" ", Arrays.copyOfRange(f, 2, f.length)) : "unknown";
                    }
                }
                case "COMPILE" -> {
                    if (compileRc == null && f.length == 4) {
                        Integer rc = parseInt(f[2]);
                        byte[] body = decode(f[3]);
                        if (rc != null && body != null) {
                            compileRc = rc;
                            compileOut = utf8(body, outputMaxBytes);
                        }
                    }
                }
                case "CASE" -> {
                    if (compileRc == null || f.length != 7) {
                        break;
                    }
                    Integer idx = parseInt(f[2]);
                    Integer rc = parseInt(f[3]);
                    Long ms = parseLong(f[4]);
                    byte[] so = decode(f[5]);
                    byte[] se = decode(f[6]);
                    if (idx == null || idx < 0 || rc == null || ms == null || so == null || se == null
                            || !seen.add(idx)) {
                        break;
                    }
                    cases.add(new SandboxResult.CaseRun(idx, rc, rc == 124, Math.max(0, ms),
                            utf8(so, outputMaxBytes), so.length > outputMaxBytes,
                            utf8(se, outputMaxBytes), se.length > outputMaxBytes));
                }
                case "END" -> ended = true;
                default -> {
                    // 未知行忽略
                }
            }
            if (ended || fatal != null) {
                break;
            }
        }
        cases.sort((a, b) -> Integer.compare(a.index(), b.index()));
        return new Parsed(begun, ended, fatal, compileRc, compileOut, List.copyOf(cases));
    }

    private static String utf8(byte[] b, int max) {
        int n = Math.min(b.length, Math.max(0, max));
        return new String(b, 0, n, StandardCharsets.UTF_8);
    }

    private static byte[] decode(String field) {
        if (field.equals("-")) {
            return new byte[0];
        }
        try {
            return Base64.getDecoder().decode(field);
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private static Integer parseInt(String s) {
        try {
            return Integer.parseInt(s);
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private static Long parseLong(String s) {
        try {
            return Long.parseLong(s);
        } catch (NumberFormatException e) {
            return null;
        }
    }
}
